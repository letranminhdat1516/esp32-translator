#!/usr/bin/env python3
"""Draw the Live Translator mark ("conversation ring") and write it where it is used:

    firmware/main/logo_img.c/.h          lock face: the mark on black, LOGO_SIZE px, LVGL 9 RGB565
    ios/Sources/Assets.xcassets/AppIcon.appiconset/icon-1024.png   iOS app icon, 1024 px on the icon ground

Two half rings chase each other (blue: you, light: them) around a small flame. The shapes are the ones in
assets/translator-mark.svg, in its 100-unit viewBox; everything is computed here with 4x4 supersampling,
so the output is deterministic.

Regenerate (needs Pillow):
    python3 -m venv /tmp/logo-venv && /tmp/logo-venv/bin/pip install pillow
    /tmp/logo-venv/bin/python tools/gen_logo.py                  # writes all outputs
    /tmp/logo-venv/bin/python tools/gen_logo.py --preview /tmp/logo_preview.png   # also render the board logo back
"""
import argparse
import math
import os

from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_C = os.path.join(ROOT, "firmware", "main", "logo_img.c")
OUT_H = os.path.join(ROOT, "firmware", "main", "logo_img.h")
OUT_ICON_DIR = os.path.join(ROOT, "ios", "Sources", "Assets.xcassets", "AppIcon.appiconset")
LOGO_SIZE = 180
SS = 4

BLUE = (0x1E, 0x6F, 0xD9)
LIGHT = (0xE3, 0xEA, 0xF0)
FLAME = (0x4C, 0x8F, 0xE8)
ICON_GROUND = (0x11, 0x13, 0x18)
BLACK = (0, 0, 0)


def polar(r, deg):
    a = math.radians(deg)
    return (50 + r * math.cos(a), 50 + r * math.sin(a))


def arc(r, a0, a1, cx=50.0, cy=50.0, steps=96):
    out = []
    for i in range(steps + 1):
        a = math.radians(a0 + (a1 - a0) * i / steps)
        out.append((cx + r * math.cos(a), cy + r * math.sin(a)))
    return out


def cubic(p0, p1, p2, p3, steps=32):
    out = []
    for i in range(1, steps + 1):
        t = i / steps
        u = 1 - t
        out.append((u ** 3 * p0[0] + 3 * u * u * t * p1[0] + 3 * u * t * t * p2[0] + t ** 3 * p3[0],
                    u ** 3 * p0[1] + 3 * u * u * t * p1[1] + 3 * u * t * t * p2[1] + t ** 3 * p3[1]))
    return out


def half_ring(start):
    """A 150 degree band (radius 20..34) from `start`, ending in an arrow head that points along the ring"""
    end = start + 150
    pts = arc(34, start, end)
    pts += [polar(38, end), polar(27, end + 22), polar(16, end)]
    pts += arc(20, end, start)
    return pts


def flame():
    p = [(50, 37)]
    p += cubic((50, 37), (56, 44), (60, 49), (60, 55))
    p += arc(10, 0, 180, cx=50, cy=55)
    p += cubic((40, 55), (40, 50), (44, 47), (46, 43))
    p += cubic((46, 43), (47, 47), (48, 48), (50, 49))
    p += cubic((50, 49), (50, 45), (49, 41), (50, 37))
    return p


SHAPES = [(half_ring(-170), BLUE), (half_ring(10), LIGHT), (flame(), FLAME)]


def render(size, ground, view=(0, 0, 100, 100)):
    """The mark over `ground`, the viewBox `view` (x, y, w, h) mapped onto a size x size image"""
    big = size * SS
    im = Image.new("RGB", (big, big), ground)
    d = ImageDraw.Draw(im)
    vx, vy, vw, vh = view
    for pts, color in SHAPES:
        d.polygon([((x - vx) * big / vw, (y - vy) * big / vh) for x, y in pts], fill=color)
    return im.resize((size, size), Image.LANCZOS)


def rgb565(im):
    data = bytearray()
    raw = im.tobytes()
    for r, g, b in zip(raw[0::3], raw[1::3], raw[2::3]):
        v = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
        data += bytes((v & 0xFF, v >> 8))
    return bytes(data)


def write_firmware(w, h, data):
    lines = []
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join("0x%02x" % x for x in data[i:i + 24]) + ",")
    with open(OUT_C, "w") as f:
        f.write("/* Generated by tools/gen_logo.py (the Live Translator mark). Do not edit; edit the script and re-run it. */\n")
        f.write('#include "logo_img.h"\n\n')
        f.write("static const uint8_t logo_map[%d] = {\n" % len(data))
        f.write("\n".join(lines) + "\n};\n\n")
        f.write("const lv_image_dsc_t logo_img = {\n"
                "    .header.magic = LV_IMAGE_HEADER_MAGIC,\n"
                "    .header.cf = LV_COLOR_FORMAT_RGB565,\n"
                "    .header.w = %d,\n    .header.h = %d,\n    .header.stride = %d,\n"
                "    .data_size = sizeof(logo_map),\n    .data = logo_map,\n};\n" % (w, h, w * 2))
    with open(OUT_H, "w") as f:
        f.write('#pragma once\n#include <stdint.h>\n#include "lvgl.h"\n'
                "#define LOGO_W %d\n#define LOGO_H %d\nextern const lv_image_dsc_t logo_img;\n" % (w, h))


def write_icon():
    os.makedirs(OUT_ICON_DIR, exist_ok=True)
    render(1024, ICON_GROUND).save(os.path.join(OUT_ICON_DIR, "icon-1024.png"))
    with open(os.path.join(OUT_ICON_DIR, "Contents.json"), "w") as f:
        f.write('{\n  "images" : [\n    {\n      "filename" : "icon-1024.png",\n      "idiom" : "universal",\n'
                '      "platform" : "ios",\n      "size" : "1024x1024"\n    }\n  ],\n'
                '  "info" : {\n    "author" : "xcode",\n    "version" : 1\n  }\n}\n')
    with open(os.path.join(os.path.dirname(OUT_ICON_DIR), "Contents.json"), "w") as f:
        f.write('{\n  "info" : {\n    "author" : "xcode",\n    "version" : 1\n  }\n}\n')


def preview(path, w, h, data):
    px = []
    for i in range(0, len(data), 2):
        v = data[i] | (data[i + 1] << 8)
        r, g, b = (v >> 11) & 31, (v >> 5) & 63, v & 31
        px.append(((r << 3) | (r >> 2), (g << 2) | (g >> 4), (b << 3) | (b >> 2)))
    im = Image.new("RGB", (w, h))
    im.putdata(px)
    im.save(path)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--preview", metavar="PNG")
    a = ap.parse_args()
    # The board logo is cropped to the mark (viewBox 12..88), so it fills its LOGO_SIZE square
    board = render(LOGO_SIZE, BLACK, view=(12, 12, 76, 76))
    data = rgb565(board)
    write_firmware(LOGO_SIZE, LOGO_SIZE, data)
    write_icon()
    if a.preview:
        preview(a.preview, LOGO_SIZE, LOGO_SIZE, data)
    print("logo_img %dx%d, %d bytes; app icon 1024 px" % (LOGO_SIZE, LOGO_SIZE, len(data)))
