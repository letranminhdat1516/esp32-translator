#!/usr/bin/env python3
"""Generate the lock-face logo: assets/cicca-dark.png -> firmware/main/logo_img.c/.h

The PNG (light letters + red dragon, transparent background) is scaled to 300 px wide
(aspect kept, Lanczos), composited onto black with its alpha channel, and written as an
LVGL 9 lv_image_dsc_t `logo_img` in RGB565, little-endian, stride = w * 2. Output is deterministic.

Regenerate (needs Pillow):
    python3 -m venv /tmp/logo-venv && /tmp/logo-venv/bin/pip install pillow
    /tmp/logo-venv/bin/python tools/gen_logo.py            # writes firmware/main/logo_img.{c,h}
    /tmp/logo-venv/bin/python tools/gen_logo.py --preview /tmp/logo_preview.png   # also render it back
"""
import argparse
import os

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "assets", "cicca-dark.png")
OUT_C = os.path.join(ROOT, "firmware", "main", "logo_img.c")
OUT_H = os.path.join(ROOT, "firmware", "main", "logo_img.h")
WIDTH = 300


def build():
    im = Image.open(SRC).convert("RGBA")
    h = max(1, round(im.height * WIDTH / im.width))
    im = im.resize((WIDTH, h), Image.LANCZOS)
    bg = Image.new("RGBA", im.size, (0, 0, 0, 255))
    rgb = Image.alpha_composite(bg, im).convert("RGB")
    data = bytearray()
    raw = rgb.tobytes()
    for r, g, b in zip(raw[0::3], raw[1::3], raw[2::3]):
        v = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
        data += bytes((v & 0xFF, v >> 8))
    return WIDTH, h, bytes(data)


def write(w, h, data):
    lines = []
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join("0x%02x" % x for x in data[i:i + 24]) + ",")
    with open(OUT_C, "w") as f:
        f.write("/* Generated by tools/gen_logo.py from assets/cicca-dark.png. Do not edit; edit the script and re-run it. */\n")
        f.write('#include "logo_img.h"\n\n')
        f.write("static const uint8_t logo_map[%d] = {\n" % len(data))
        f.write("\n".join(lines) + "\n};\n\n")
        f.write("const lv_image_dsc_t logo_img = {\n"
                "    .header.magic = LV_IMAGE_HEADER_MAGIC,\n"
                "    .header.cf = LV_COLOR_FORMAT_RGB565,\n"
                "    .header.w = %d,\n    .header.h = %d,\n    .header.stride = %d,\n"
                "    .data_size = sizeof(logo_map),\n    .data = logo_map,\n};\n" % (w, h, w * 2))
    with open(OUT_H, "w") as f:
        f.write('#pragma once\n#include <stdint.h>\n#include "lvgl.h"\n'
                "#define LOGO_W %d\n#define LOGO_H %d\nextern const lv_image_dsc_t logo_img;\n" % (w, h))


def preview(path, w, h, data):
    px = []
    for i in range(0, len(data), 2):
        v = data[i] | (data[i + 1] << 8)
        r, g, b = (v >> 11) & 31, (v >> 5) & 63, v & 31
        px.append(((r << 3) | (r >> 2), (g << 2) | (g >> 4), (b << 3) | (b >> 2)))
    im = Image.new("RGB", (w, h))
    im.putdata(px)
    im.save(path)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--preview", metavar="PNG")
    a = ap.parse_args()
    w, h, data = build()
    write(w, h, data)
    if a.preview:
        preview(a.preview, w, h, data)
    print("logo_img %dx%d, %d bytes" % (w, h, len(data)))
