#!/usr/bin/env python3
"""Generates the lock-face pixel cat (original art) as LVGL RGB565 images.

The cat is drawn here as a 32x32 character grid, upscaled x3 to 96x96 pixels, and written as
firmware/main/cat_frames.c. The board shows it at x2 (192x192) with antialiasing off.
Plain Python 3, no dependencies. Run from the repo root:  python3 tools/gen_cat.py
"""
import os
import sys

SIZE = 32          # logical grid
UPSCALE = 3        # 32 * 3 = 96 px per side in flash
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "firmware", "main", "cat_frames.c")

PALETTE = {
    ".": (0x00, 0x00, 0x00),   # background: the lock face is black
    "L": (0x6b, 0x3a, 0x14),   # outline, dark brown (visible on black)
    "O": (0xf0, 0xa0, 0x40),   # orange fur
    "D": (0xc0, 0x6a, 0x20),   # tabby stripes
    "W": (0xf4, 0xee, 0xe0),   # muzzle, chest, paws
    "N": (0xf0, 0x88, 0x90),   # nose, inner ears
    "E": (0x8c, 0xe0, 0x6a),   # eyes
    "P": (0x18, 0x18, 0x18),   # pupils, mouth
}

# Sitting cat, front view; tail drawn separately. Columns 0..31.
BODY = [
    "................................",  # 0
    "................................",  # 1
    "....L..............L............",  # 2
    "....LL............LL............",  # 3
    "....LOL..........LOL............",  # 4
    "....LNOL........LONL............",  # 5
    "....LNOOLLLLLLLLOONL............",  # 6
    "....LOOOODDODDOOOOOL............",  # 7
    "...LOOOOOODDDDOOOOOOL...........",  # 8 (head widens by one on each side)
    "...LOOOOOOOOOOOOOOOOL...........",  # 9
    "...LOOEEEOOOOOOEEEOOL...........",  # 10 eyes
    "...LOOEPEOOOOOOEPEOOL...........",  # 11
    "...LDOOOOOOWWOOOOOODL...........",  # 12
    "...LOOOOOWWNNWWOOOOOL...........",  # 13 nose
    "....LOOOOWWPPWWOOOOL............",  # 14 mouth
    ".....LLOOOWWWWOOOLL.............",  # 15 chin
    "......LOOOOWWOOOOL..............",  # 16 neck
    ".....LOOOOWWWWOOOOL.............",  # 17
    ".....LODOOWWWWOODOL.............",  # 18
    "....LOODOOWWWWOODOOL............",  # 19
    "....LOOOOWWWWWWOOOOL............",  # 20
    "....LODOOWWWWWWOODOL............",  # 21
    "....LOODOWWWWWWODOOL............",  # 22
    "....LOOOOWWWWWWOOOOL............",  # 23
    "....LOODOOWWWWOODOOL............",  # 24
    "....LOOOOOWWWWOOOOOL............",  # 25
    "....LOOOOOOWWOOOOOOL............",  # 26
    "....LOOLWWLOOLWWLOOL............",  # 27 front paws
    "....LOOLWWWLLWWWLOOL............",  # 28
    ".....LLLLLLLLLLLLLL.............",  # 29
    "................................",  # 30
    "................................",  # 31
]

# Tail positions: (row, col) cells painted "O" with a "D" tip (last cell).
TAILS = {
    "down": [(28, 20), (28, 21), (28, 22), (28, 23), (27, 24), (27, 25), (26, 26), (25, 26)],
    "mid":  [(28, 20), (28, 21), (27, 22), (26, 23), (25, 23), (24, 24), (23, 24), (22, 24)],
    "up":   [(28, 20), (27, 21), (26, 22), (25, 22), (24, 22), (23, 22), (22, 23), (21, 24), (20, 24)],
}

EYES_CLOSED = {(10, 6): "O", (10, 7): "O", (10, 8): "O", (11, 6): "P", (11, 7): "P", (11, 8): "P",
               (10, 15): "O", (10, 16): "O", (10, 17): "O", (11, 15): "P", (11, 16): "P", (11, 17): "P"}

# Unique images, then the order the board plays them (one step every CAT_FRAME_MS on the board)
FRAMES = [("down", False), ("mid", False), ("up", False), ("down", True)]
SEQUENCE = [0, 0, 1, 2, 1, 0, 0, 3, 0, 0, 1, 2, 2, 1]


def grid(tail, blink):
    g = [list(row) for row in BODY]
    cells = TAILS[tail]
    for i, (r, c) in enumerate(cells):
        g[r][c] = "D" if i == len(cells) - 1 else "O"
        g[r + 1][c] = "O" if g[r + 1][c] == "." else g[r + 1][c]   # two cells thick
    if blink:
        for (r, c), ch in EYES_CLOSED.items():
            g[r][c] = ch
    return g


def rgb565_le(rgb):
    r, gr, b = rgb
    v = ((r >> 3) << 11) | ((gr >> 2) << 5) | (b >> 3)
    return (v & 0xFF, v >> 8)


def frame_bytes(g):
    out = bytearray()
    for row in g:
        line = bytearray()
        for ch in row:
            lo, hi = rgb565_le(PALETTE[ch])
            line += bytes((lo, hi)) * UPSCALE
        out += bytes(line) * UPSCALE
    return out


def check():
    for i, row in enumerate(BODY):
        if len(row) != SIZE:
            sys.exit(f"BODY row {i} has {len(row)} columns, expected {SIZE}")
        bad = set(row) - set(PALETTE)
        if bad:
            sys.exit(f"BODY row {i} uses unknown colours {bad}")
    if len(BODY) != SIZE:
        sys.exit(f"BODY has {len(BODY)} rows, expected {SIZE}")
    for name, cells in TAILS.items():
        for r, c in cells:
            if not (0 <= r < SIZE - 1 and 0 <= c < SIZE):
                sys.exit(f"tail {name} cell {(r, c)} is off the grid")
    if any(i >= len(FRAMES) for i in SEQUENCE):
        sys.exit("SEQUENCE refers to a missing frame")


def main():
    check()
    px = SIZE * UPSCALE
    parts = [
        "/* Generated by tools/gen_cat.py: original pixel art. Do not edit; edit the script and re-run it. */\n",
        '#include "cat_frames.h"\n\n',
    ]
    for n, (tail, blink) in enumerate(FRAMES):
        data = frame_bytes(grid(tail, blink))
        assert len(data) == px * px * 2
        parts.append(f"static const uint8_t frame{n}_map[{len(data)}] = {{\n")
        for off in range(0, len(data), 24):
            parts.append("    " + ", ".join(f"0x{b:02x}" for b in data[off:off + 24]) + ",\n")
        parts.append("};\n\n")
        parts.append(
            f"static const lv_image_dsc_t frame{n} = {{\n"
            f"    .header.magic = LV_IMAGE_HEADER_MAGIC,\n"
            f"    .header.cf = LV_COLOR_FORMAT_RGB565,\n"
            f"    .header.w = {px},\n"
            f"    .header.h = {px},\n"
            f"    .header.stride = {px * 2},\n"
            f"    .data_size = sizeof(frame{n}_map),\n"
            f"    .data = frame{n}_map,\n"
            f"}};\n\n")
    parts.append("const lv_image_dsc_t *const cat_frames[] = { "
                 + ", ".join(f"&frame{n}" for n in range(len(FRAMES))) + " };\n")
    parts.append(f"const int cat_frame_count = {len(FRAMES)};\n")
    parts.append("const uint8_t cat_sequence[] = { " + ", ".join(str(i) for i in SEQUENCE) + " };\n")
    parts.append(f"const int cat_sequence_len = {len(SEQUENCE)};\n")
    with open(OUT, "w") as f:
        f.write("".join(parts))
    print(f"wrote {os.path.normpath(OUT)}: {len(FRAMES)} frames of {px}x{px} RGB565, "
          f"{len(FRAMES) * px * px * 2} bytes of pixels")
    if "--preview" in sys.argv:
        for tail, blink in FRAMES:
            print(f"--- tail {tail}, blink {blink}")
            print("\n".join("".join(r) for r in grid(tail, blink)))


if __name__ == "__main__":
    main()
